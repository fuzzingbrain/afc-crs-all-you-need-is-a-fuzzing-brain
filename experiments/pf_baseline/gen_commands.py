#!/usr/bin/env python3
"""Emit manifest.json, commands.sh and cmd/<id>.sh for the 40 pure-fuzzing runs.

One command per target: the organizer-built ASan harness from the per-bug
bundle, run under libFuzzer ``-fork=$PF_FORK`` for the target's time limit,
with the seed corpus that the pinned OSS-Fuzz build would have produced
(build_corpus.py) and the ``.options``/``.dict`` extras run_fuzzer would apply.

The docker line mirrors fuzzingbrain/fuzzer/instance.py (same image, env,
cgroup caps, libFuzzer flags) so that the baseline and FBv2's own Global
Fuzzer differ only in fork level and in the absence of the agents.

Environment knobs (read when a command executes, not when it is generated):
  PF_FORK        libFuzzer -fork level and the container's --cpus  (required)
  PF_TIME_DELTA  seconds for delta targets   (default 3600)
  PF_TIME_FULL   seconds for full targets    (default 7200)
  PF_RUN         run tag -> runs/<tag>/<id>/ (default: pf-<date>)
  PF_RSS_MB      per-process rss limit       (default 2048, FBv2 global default)
  PF_IMAGE       runner image                (default ghcr.io/aixcc-finals/base-runner:v1.3.0)
"""
from __future__ import annotations

import json
import os
import stat
from pathlib import Path

from build_corpus import TARGETS

HERE = Path(__file__).resolve().parent
BIN_ROOT = Path(os.environ.get(
    "PF_BIN_ROOT",
    "/home/ze/afc-crs-all-you-need-is-a-fuzzing-brain/examples/aixcc-challenges/final-competition"))
REPRO_ROOT = Path("/home/ze/fbv2/examples/aixcc-challenges/final-competition")
NO_OOM_MEMORY_MB = 24576     # FBv2 uses 8192 (fuzzer_spec.py); at 10 GB the dav1d @NO_OOM fork run was cgroup-killed after 120 s


def so_dirs(bin_dir: Path) -> list[str]:
    rels = sorted({str(p.parent.relative_to(bin_dir)) for p in bin_dir.rglob("*.so*") if p.is_file()})
    return rels


def main() -> None:
    corpus = json.loads((HERE / "corpus_manifest.json").read_text())
    manifest = []
    lines = ["#!/usr/bin/env bash",
             "# 40 pure-fuzzing commands, one per AIxCC C target. Generated by gen_commands.py.",
             "# Every command needs PF_FORK (see README). Run them one at a time (concurrency 1).",
             "set -u", "cd \"$(dirname \"${BASH_SOURCE[0]}\")\"", ""]
    (HERE / "cmd").mkdir(exist_ok=True)
    per_harness: dict[tuple[str, str], int] = {}
    for _, _, ch, _, _, harness in TARGETS:
        per_harness[(ch, harness)] = per_harness.get((ch, harness), 0) + 1

    for tid, mode, ch, bug, proj, harness in TARGETS:
        bin_dir = BIN_ROOT / mode / ch / "bugs" / bug / "bin" / "address"
        repro = REPRO_ROOT / mode / ch / "bugs" / bug
        bugmeta = json.loads((repro / "bug.json").read_text())
        wrapper = harness.endswith((".Convert",)) or "@" in harness
        no_oom = harness.endswith("@NO_OOM")
        sos = so_dirs(bin_dir)
        extra = corpus[tid]["libfuzzer_extra"]
        tlimit = "${PF_TIME_DELTA:-3600}" if mode == "delta" else "${PF_TIME_FULL:-7200}"
        entry = {
            "id": tid, "mode": mode, "challenge": ch, "bug": bug, "project": proj,
            "harness": harness, "bin_dir": str(bin_dir), "wrapper": wrapper, "no_oom": no_oom,
            "ld_library_path": ":".join(f"/fuzzers/{d}" for d in sos) if sos else "",
            "seeds": corpus[tid]["seeds"], "corpus_dir": f"corpus/{tid}",
            "cfg_dir": f"cfg/{tid}" if (HERE / "cfg" / tid).exists() else "",
            "libfuzzer_extra": extra,
            "time_limit_env": "PF_TIME_DELTA" if mode == "delta" else "PF_TIME_FULL",
            "time_limit_default": 3600 if mode == "delta" else 7200,
            "repro_sh": str(repro / "repro.sh"), "blob": str(repro / "blob"),
            "expect": None, "crash_file": bugmeta["consistency"].get("crash_file"),
            "crash_line": bugmeta["consistency"].get("crash_line"),
            "shared_harness": per_harness[(ch, harness)] > 1,
        }
        manifest.append(entry)

        mem = f"$(( {NO_OOM_MEMORY_MB} + ${{PF_RSS_MB:-2048}} * (${{PF_FORK:?}} - 1) ))" if no_oom \
            else "$(( ${PF_RSS_MB:-2048} * ${PF_FORK:?} + 1024 ))"
        oom = "-rss_limit_mb=0 -malloc_limit_mb=0" if no_oom else "-rss_limit_mb=${PF_RSS_MB:-2048}"
        # wrapper scripts chmod their sibling binary, so they need a writable
        # copy of the bin dir; plain libFuzzer targets mount the bundle read-only.
        fz_mount = "$PWD/$RUN/bin:/fuzzers" if wrapper else f"{bin_dir}:/fuzzers:ro"
        cfg_mount = f" -v {HERE}/cfg/{tid}:/cfg:ro" if entry["cfg_dir"] else ""
        ld = f" -e LD_LIBRARY_PATH={entry['ld_library_path']}" if sos else ""
        cmd = (
            f"RUN=runs/${{PF_RUN:-pf-$(date +%F)}}/{tid}; T={tlimit}; "
            f"timeout $((T + 300)) docker run --rm --platform linux/amd64 --entrypoint '' "
            f"--label pf_baseline={tid} --memory={mem}m --memory-swap={mem}m --cpus=${{PF_FORK:?}} --pids-limit=512 "
            f"-e FUZZING_ENGINE=libfuzzer -e SANITIZER=address -e ARCHITECTURE=x86_64 -e ASAN_OPTIONS=detect_leaks=0{ld} "
            f"-v {fz_mount} -v $PWD/$RUN/corpus:/corpus -v $PWD/$RUN/crashes:/crashes{cfg_mount} "
            f"${{PF_IMAGE:-ghcr.io/aixcc-finals/base-runner:v1.3.0}} "
            f"'/fuzzers/{harness}' /corpus -artifact_prefix=/crashes/ -fork=${{PF_FORK:?}} -ignore_crashes=1 "
            f"{oom} -timeout=30 -print_final_stats=1 -max_total_time=$T{(' ' + ' '.join(extra)) if extra else ''} "
            f"> $RUN/fuzz.log 2>&1"
        )
        lines.append(f"# {tid}: {ch} / {bug} / {harness} ({mode}, {corpus[tid]['seeds']} seeds)")
        lines.append(f"./run_one.sh {tid}   # ->  {cmd}")
        lines.append("")
        script = HERE / "cmd" / f"{tid}.sh"
        script.write_text("#!/usr/bin/env bash\n# generated by gen_commands.py; invoked by run_one.sh with cwd = pf_baseline\nset -u\n" + cmd + "\n")
        script.chmod(script.stat().st_mode | stat.S_IEXEC)

    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    out = HERE / "commands.sh"
    out.write_text("\n".join(lines) + "\n")
    out.chmod(out.stat().st_mode | stat.S_IEXEC)
    print(f"wrote manifest.json ({len(manifest)}), commands.sh, cmd/*.sh")


if __name__ == "__main__":
    main()
